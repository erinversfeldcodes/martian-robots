//! Derive this implementation's constants from the contract it is graded
//! against.
//!
//! The limits and the vocabularies are facts the contract states once. Writing
//! them out again here would make this crate a second place for them to live,
//! and a second place is where drift happens: a coordinate limit raised in the
//! contract and missed here is a conformance failure that looks like a bug.
//!
//! So they are read, at build time, out of the pinned release. The suite is a
//! build dependency only, and none of it is linked into the program.

use std::fmt::Write as _;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let contract = martian_robots_verify::contract::Contract::load()
        .expect("the pinned release to carry a coherent contract");

    let mut derived = String::new();
    derived.push_str("// Generated by build.rs from the pinned contract. Do not edit.\n");

    let _ = writeln!(
        derived,
        "/// The contract version these constants came from.\n\
         pub const VERSION: &str = {:?};",
        contract.version
    );
    let _ = writeln!(
        derived,
        "/// The largest coordinate a grid line or a robot may name.\n\
         pub const MAX_COORDINATE: u32 = {};",
        contract.limits.max_coordinate
    );
    let _ = writeln!(
        derived,
        "/// The longest instruction string a robot may carry.\n\
         pub const MAX_INSTRUCTIONS: usize = {};",
        contract.limits.max_instructions
    );
    let _ = writeln!(
        derived,
        "/// The orientations, in the order the grammar lists them.\n\
         pub const ORIENTATIONS: [char; {}] = {:?};",
        contract.grammar.orientations.len(),
        contract.grammar.orientations
    );
    let _ = writeln!(
        derived,
        "/// The instructions, in the order the grammar lists them.\n\
         pub const INSTRUCTIONS: [char; {}] = {:?};",
        contract.grammar.instructions.len(),
        contract.grammar.instructions
    );
    let _ = writeln!(
        derived,
        "/// The characters that separate tokens. Runs of these, and nothing\n\
         /// else, are whitespace to this contract.\n\
         pub const SEPARATORS: [char; {}] = {:?};",
        contract.grammar.separators.len(),
        contract.grammar.separators
    );

    let out = std::path::Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("contract.rs");
    std::fs::write(&out, derived).expect("to write the derived contract");
}
